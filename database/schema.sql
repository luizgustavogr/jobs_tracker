create table if not exists public.applications (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  title text not null,
  company text not null,
  location text,
  link text,
  description text,
  status text not null default 'Aplicado',
  origin text not null default 'Brasileira',
  applied_date date not null default current_date,
  created_at timestamptz not null default now(),
  constraint applications_status_check
    check (status in ('Aplicado', 'Em análise', 'Entrevista', 'Entrevista RH', 'Entrevista Técnica', 'Entrevista Diretoria', 'Entrevista Cliente', 'Oferta')),
  constraint applications_origin_check
    check (origin in ('Brasileira', 'Gringa'))
);

alter table public.applications add column if not exists origin text not null default 'Brasileira';
alter table public.applications add column if not exists link text;
-- Registros antigos ficam com user_id nulo (e invisíveis) até serem atribuídos a um usuário.
-- Depois do primeiro login, execute separadamente, trocando pelo seu e-mail:
--   update public.applications
--   set user_id = (select id from auth.users where email = 'seu-email@gmail.com')
--   where user_id is null;
alter table public.applications add column if not exists user_id uuid default auth.uid() references auth.users (id) on delete cascade;
update public.applications set origin = 'Brasileira' where origin is null;
alter table public.applications drop constraint if exists applications_status_check;
alter table public.applications add constraint applications_status_check
  check (status in ('Aplicado', 'Em análise', 'Entrevista', 'Entrevista RH', 'Entrevista Técnica', 'Entrevista Diretoria', 'Entrevista Cliente', 'Oferta'));
alter table public.applications drop constraint if exists applications_origin_check;
alter table public.applications add constraint applications_origin_check
  check (origin in ('Brasileira', 'Gringa'));

-- Validação no servidor: o front-end não é uma barreira, qualquer cliente pode chamar a API.
-- "not valid" não reprocessa linhas antigas, mas vale para todo insert/update novo.
alter table public.applications drop constraint if exists applications_limits_check;
alter table public.applications add constraint applications_limits_check check (
  char_length(title) between 1 and 200
  and char_length(company) between 1 and 200
  and char_length(location) <= 200
  and char_length(description) <= 20000
  and (link is null or (char_length(link) <= 2048 and link ~* '^https?://'))
) not valid;

create index if not exists applications_user_id_idx on public.applications (user_id);

alter table public.applications enable row level security;

drop policy if exists "Acesso público para visualizar candidaturas" on public.applications;
drop policy if exists "Acesso público para criar candidaturas" on public.applications;
drop policy if exists "Acesso público para excluir candidaturas" on public.applications;
drop policy if exists "Acesso público para editar candidaturas" on public.applications;
drop policy if exists "Usuário visualiza suas candidaturas" on public.applications;
drop policy if exists "Usuário cria suas candidaturas" on public.applications;
drop policy if exists "Usuário edita suas candidaturas" on public.applications;
drop policy if exists "Usuário exclui suas candidaturas" on public.applications;

create policy "Usuário visualiza suas candidaturas"
on public.applications for select to authenticated using (auth.uid() = user_id);

create policy "Usuário cria suas candidaturas"
on public.applications for insert to authenticated with check (auth.uid() = user_id);

create policy "Usuário edita suas candidaturas"
on public.applications for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

create policy "Usuário exclui suas candidaturas"
on public.applications for delete to authenticated using (auth.uid() = user_id);
